/**
 * 祝日データが入っている最後の年。
 * 年を追加したらここも上げること（画面の「祝日データ未登録」警告の基準になる）。
 */
export const HOLIDAY_DATA_LAST_YEAR = 2028;

/** 'YYYY-MM-DD' の祝日名。祝日でなければ undefined */
export function holidayName(dateKey: string): string | undefined {
  return HOLIDAYS[dateKey];
}

/**
 * その日付が祝日データの範囲外か（＝祝日かどうか判定できない）。
 * 範囲外の期間は祝日が全部平日扱いになってしまうため、画面側で警告を出す。
 * 引数は 'YYYY-MM-DD' でも 'YYYY-MM' でもよい。
 */
export function isBeyondHolidayData(dateKeyOrMonth: string): boolean {
  const year = Number(dateKeyOrMonth.slice(0, 4));
  return Number.isFinite(year) && year > HOLIDAY_DATA_LAST_YEAR;
}

/** 警告文。画面にそのまま出せる */
export function holidayDataWarning(): string {
  return `⚠️ ${HOLIDAY_DATA_LAST_YEAR}年までの祝日しか登録されていません。`
    + `この期間は祝日が平日として扱われます（土日の色分けは正常です）。`;
}
